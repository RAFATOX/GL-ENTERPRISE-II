export function normalizeLanguageId(value) {
  const normalized = String(value || "").toLowerCase().replace("_", "-");
  if (!normalized) return defaultLanguageId;
  const exact = languageOptions.find((item) => item.id === normalized);
  if (exact) return exact.id;
  const base = normalized.split("-")[0];
  return languageOptions.find((item) => item.id === base)?.id || defaultLanguageId;
}

export function detectDeviceLanguage(value) {
  return normalizeLanguageId(value || defaultLanguageId);
}

export function languageOptionFor(languageId) {
  const normalized = normalizeLanguageId(languageId);
  return languageOptions.find((item) => item.id === normalized) || languageOptions[0];
}

export function searchIndexForLanguage(option) {
  return [
    option.id,
    option.country,
    option.countryName,
    option.languageName
  ].join(" ").toLowerCase();
}
