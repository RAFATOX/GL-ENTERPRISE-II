export function t(key, params = {}, language = DEFAULT_LANGUAGE) {
  const activeLanguage = dictionaries[language] ? language : DEFAULT_LANGUAGE;
  const value = dictionaries[activeLanguage][key] || dictionaries[DEFAULT_LANGUAGE][key] || key;
  return interpolate(value, params);
}

export function validation(key, params = {}, language = DEFAULT_LANGUAGE) {
  return t(`validation.${key}`, params, language);
}

export function translateValue(value, language = DEFAULT_LANGUAGE) {
  if (value === null || value === undefined) return "";
  const text = String(value);
  if (dictionaries[language]?.[text] || dictionaries[DEFAULT_LANGUAGE]?.[text]) return t(text, {}, language);
  const legacyKey = legacyMessageKeys[text];
  if (legacyKey) return t(legacyKey, {}, language);
  if (codeLabels[text]) return codeLabels[text];
  return text
    .replace(/transport status must be ([^,]+), current: (.+)/, (_, expected, current) => (
      t("validation.transport_status_expected", { expected: translateValue(expected, language), current: translateValue(current, language) }, language)
    ))
    .replace(/expected status ([^,]+), current: (.+)/, (_, expected, current) => (
      t("validation.transport_status_expected", { expected: translateValue(expected, language), current: translateValue(current, language) }, language)
    ))
    .replace(/transport must be ([^,]+) before carrier acceptance, current: (.+)/, (_, expected, current) => (
      t("validation.transport_status_expected", { expected: translateValue(expected, language), current: translateValue(current, language) }, language)
    ))
    .replace(/transport must be ([^,]+) before driver assignment, current: (.+)/, (_, expected, current) => (
      t("validation.transport_status_expected", { expected: translateValue(expected, language), current: translateValue(current, language) }, language)
    ));
}

export function localizeText(input, language = DEFAULT_LANGUAGE) {
  return translateValue(input, language);
}

function interpolate(template, params) {
  return String(template).replace(/\{([a-zA-Z0-9_]+)\}/g, (_, key) => (
    params[key] === undefined || params[key] === null ? "" : String(params[key])
  ));
}
